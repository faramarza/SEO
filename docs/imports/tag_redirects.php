<?php
/**
 * TAG Toys closed (2026-11): permanent (301) redirects from the old product URLs
 * to in-stock replacements, for the alphabettrains store view.
 *
 * Run from the Magento root (the folder with app/ and bin/):
 *   php tag_redirects.php            -> dry run: shows what it WOULD do, changes nothing
 *   php tag_redirects.php --apply    -> adds the redirects
 *   php tag_redirects.php --undo     -> removes exactly the redirects this script added
 * Then: bin/magento cache:flush
 *
 * Safety: an address still used by a product (or anything else) is SKIPPED and
 * reported, never overwritten. The one exception: Magento's own automatic 301
 * from an old address to the renamed "-discontinued" page is re-pointed to the
 * replacement (only when it targets exactly that -discontinued address). Only rows tagged with the description below are
 * ever removed by --undo.
 */
$apply = in_array('--apply', $argv, true);
$undo  = in_array('--undo', $argv, true);
$TAG   = 'TAG Toys closed 2026-11 (Governor)';
$STORE_CODE = 'alphabettrains';
$pairs = [
    ['montessori-geometric-shapes.html', 'bench-montessori-shape-sorter.html'],
    ['montessori-geometric-tracing-board.html', 'guidecraft-magna-tablet-deluxe-drawing.html'],
    ['montessori-shape-sorter.html', 'guide-craft-wooden-shape-sorter.html'],
    ['montessori-locks-latches-board.html', 'guidecraft-peekaboo-lock-boxes-set.html'],
    ['montessori-alphabet-tracing-board.html', 'guidecraft-magna-tablet-deluxe-drawing.html'],
    ['montessori-sound-cylinders.html', 'peekaboo-sensory-sound-boxes.html'],
    ['montessori-spellmaster-toy.html', 'name-trains.html'],
    ['montessori-shape-sorter-mirror.html', 'bench-montessori-shape-sorter.html'],
    ['motor-letters-lowercase-sensory-toy.html', 'guidecraft-magna-tablet-deluxe-drawing.html'],
    ['montessori-stacking-ring.html', 'stacking-rainbow-pyramid.html'],
    ['montessori-spinning-drum.html', 'sensory-toys.html'],
    ['montessori-geometric-shapes-puzzles.html', 'bench-montessori-shape-sorter.html'],
    ['motor-shapes-board-montessori-toy.html', 'montessori-shape-stacker.html'],
    ['montessori-geometric-shapes-puzzle.html', 'kids-puzzles.html'],
    ['kids-name-puzzle-2-line.html', 'personalized-dbl-name-puzzle-html.html'],
    ['personalized-name-puzzle-2.html', 'personalized-name-puzzle.html'],
    ['alphabet-puzzle.html', 'kids-puzzles.html'],
    ['lower-case-alphabet-puzzle.html', 'kids-puzzles.html'],
    ['tag-toys-spatial-reasoning-toy.html', 'kids-puzzles.html'],
    ['montessori-size-comparison-puzzle.html', 'kids-puzzles.html'],
    ['wooden-building-blocks.html', 'wooden-blocks.html'],
    ['math-skills-number-puzzle.html', 'kids-puzzles.html'],
    ['montessori-sorting-tray.html', 'sorting-toys.html'],
    ['tumble-down-counting-pegs.html', 'sorting-toys.html'],
    ['montessori-music-box.html', 'sensory-toys.html'],
    ['multi-purpose-slant-board.html', 'guidecraft-magna-tablet-deluxe-drawing.html'],
    ['montessori-minivan-toy.html', 'pretend-play-toys.html']
];

$env = include __DIR__ . '/app/etc/env.php';
$c = $env['db']['connection']['default'];
$p = $env['db']['table_prefix'] ?? '';
$db = new PDO("mysql:host={$c['host']};dbname={$c['dbname']};charset=utf8", $c['username'], $c['password'],
              [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);

$st = $db->prepare("SELECT store_id FROM {$p}store WHERE code = ?");
$st->execute([$STORE_CODE]);
$storeId = $st->fetchColumn();
if ($storeId === false) { fwrite(STDERR, "Store view '$STORE_CODE' not found.\n"); exit(1); }
echo "Store view $STORE_CODE = store_id $storeId\n";

if ($undo) {
    $d = $db->prepare("DELETE FROM {$p}url_rewrite WHERE description = ? AND entity_type = 'custom'");
    $d->execute([$TAG]);
    echo "Removed " . $d->rowCount() . " redirects added by this script.\n";
    // re-pointed automatic redirects: send them back to the renamed product page
    $r = $db->prepare("UPDATE {$p}url_rewrite SET target_path = CONCAT(SUBSTRING(request_path, 1, CHAR_LENGTH(request_path) - 5), '-discontinued.html'), description = NULL WHERE description = ? AND entity_type <> 'custom'");
    $r->execute([$TAG]);
    echo "Restored " . $r->rowCount() . " automatic redirects to their -discontinued pages.\n";
    exit(0);
}

$find = $db->prepare("SELECT url_rewrite_id, entity_type, target_path, redirect_type, description FROM {$p}url_rewrite WHERE request_path = ? AND store_id = ?");
$repoint = $db->prepare("UPDATE {$p}url_rewrite SET target_path = ?, description = ? WHERE url_rewrite_id = ?");
$repointed = 0;
$ins  = $db->prepare("INSERT INTO {$p}url_rewrite (entity_type, entity_id, request_path, target_path, redirect_type, store_id, description, is_autogenerated, metadata) VALUES ('custom', 0, ?, ?, 301, ?, ?, 0, NULL)");
$added = $skipped = $already = 0;
foreach ($pairs as [$from, $to]) {
    $find->execute([$from, $storeId]);
    $row = $find->fetch(PDO::FETCH_ASSOC);
    if ($row) {
        if ($row['description'] === $TAG) { $already++; echo "  already done  /$from\n"; continue; }
        // Magento's own automatic redirect from the old address to the renamed
        // "-discontinued" product page: re-point it to the replacement.
        $disc = substr($from, 0, -5) . '-discontinued.html';
        if ((int)$row['redirect_type'] === 301 && $row['target_path'] === $disc) {
            if ($apply) { $repoint->execute([$to, $TAG, $row['url_rewrite_id']]); }
            $repointed++;
            echo ($apply ? "  RE-POINTED    " : "  would repoint ") . "/$from  ->  /$to  (was -> /$disc)\n";
            continue;
        }
        $skipped++;
        echo "  SKIPPED       /$from  (still used by: {$row['entity_type']} -> {$row['target_path']}). Rename that product's URL key first.\n";
        continue;
    }
    if ($apply) { $ins->execute([$from, $to, $storeId, $TAG]); }
    $added++;
    echo ($apply ? "  ADDED         " : "  would add     ") . "/$from  ->  /$to  (301)\n";
}
echo "\n" . ($apply ? "Added" : "Would add") . ": $added   " . ($apply ? "Re-pointed" : "Would re-point")
   . ": $repointed   Skipped: $skipped   Already done: $already\n";
if (!$apply) echo "Dry run only. Run again with --apply to make the changes.\n";
